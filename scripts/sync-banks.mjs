// Regenerates constant/nigerian-banks.ts from public bank directories. Run with `pnpm sync:banks`.
// Banks: Paystack's public bank list (no key needed). Logos: nigerianbanks.xyz, matched on the CBN code.
import { writeFile } from "node:fs/promises";

const BANKS_URL = "https://api.paystack.co/bank?country=nigeria&perPage=500";
const LOGOS_URL = "https://nigerianbanks.xyz";
const OUT = new URL("../constant/nigerian-banks.ts", import.meta.url);

// The banks most investors use, shown first. Short names people search for go in `aliases`.
const POPULAR = {
  "058": ["GTBank", "GTCO"],
  "044": ["Access"],
  "057": ["Zenith"],
  "011": ["First Bank", "FBN"],
  "033": ["UBA"],
  999992: ["OPay"],
  50515: ["Moniepoint"],
  50211: ["Kuda"],
  999991: ["PalmPay"],
  "035": ["Wema", "ALAT"],
  "070": ["Fidelity"],
  214: ["FCMB"],
  232: ["Sterling"],
  221: ["Stanbic", "IBTC"],
};

const fetchJson = async (url) => {
  const response = await fetch(url, { headers: { Accept: "application/json" } });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return response.json();
};

const groupOf = (name) => {
  if (/\bMFB\b|micro ?fina|mircofinance|microfinanace/i.test(name)) return "Microfinance banks";
  if (/mortgage|mortage|savings and loans|building/i.test(name)) return "Mortgage banks";
  if (
    /PSB\b|payment service|wallet|momo|smartcash|money|paga|eyowo|carbon|kegow|pocket app|^zap$|readycash|pay\b/i.test(
      name
    )
  )
    return "Payment service banks & wallets";
  if (/financ|credit|loan/i.test(name) && !/bank/i.test(name)) return "Finance companies";
  return "Banks";
};

// Some names arrive in capitals ("NOVA BANK"); keep short acronyms such as "UBA" as they are.
const tidy = (name) =>
  name === name.toUpperCase() && name.length > 5
    ? name.toLowerCase().replace(/\b[a-z]/g, (char) => char.toUpperCase())
    : name.trim();

const [{ data }, logoList] = await Promise.all([fetchJson(BANKS_URL), fetchJson(LOGOS_URL)]);
const logos = new Map(logoList.map((bank) => [bank.code, bank.logo]));

const banks = data
  .filter((bank) => bank.active && !bank.is_deleted && bank.supports_transfer && bank.currency === "NGN")
  .map((bank) => ({
    name: tidy(bank.name),
    slug: bank.slug,
    code: bank.code,
    group: POPULAR[bank.code] ? "Popular" : groupOf(bank.name),
    aliases: POPULAR[bank.code] ?? [],
    logo: logos.get(bank.code) ?? null,
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

if (banks.length < 100) throw new Error(`Only ${banks.length} banks came back; refusing to overwrite the list.`);

const file = `// Generated by scripts/sync-banks.mjs on ${new Date().toISOString().slice(0, 10)}. Don't edit by hand.
// Sources: Paystack's public bank list (active, NGN, supports transfers) and nigerianbanks.xyz logos.

export interface NigerianBank {
  name: string;
  /** Unique, unlike \`code\`: a few banks share a CBN code. */
  slug: string;
  /** CBN / NIP bank code used for transfers and account-name lookups. */
  code: string;
  group: "Popular" | "Banks" | "Payment service banks & wallets" | "Microfinance banks" | "Mortgage banks" | "Finance companies";
  /** Short names people search for, such as "GTBank". */
  aliases: string[];
  logo: string | null;
}

export const NIGERIAN_BANKS: NigerianBank[] = ${JSON.stringify(banks, null, 2)};
`;

await writeFile(OUT, file);
console.log(`Wrote ${banks.length} banks (${banks.filter((b) => b.logo).length} with logos).`);
